#!/usr/bin/env sh
# Put the Perfetto stub jar on the boot classpath of every JDK tool, so `javac`, `jar`,
# `keytool` ... work without remembering -J-Xbootclasspath/a: (see fix-termux-javac.py).
#
# Idempotent. Run again after `pkg upgrade` (which restores the $PREFIX/etc/alternatives
# symlinks) and after regenerating the stub jar.
#
# Termux: rewrites $PREFIX/etc/alternatives/<tool>.
# Anything else: writes shims into $ANDROID_TOOLS/bin and tells you to prepend it to PATH.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
LIB="$HERE/lib"; [ -f "$LIB/common.sh" ] || LIB="$HERE/../lib"
. "$LIB/common.sh"

STUB="$PERFETTO_STUB_JAR"
TOOLS="java javac jar keytool javap jshell jlink javadoc jdb jcmd jinfo jmap jps jstack serialver"

[ -f "$STUB" ] || warn "stub jar $STUB not found - run: $PY fix-termux-javac.py"

flag_for() {   # `java` takes the flag bare, the other launchers want -J
  if [ "$1" = java ]; then echo "-Xbootclasspath/a:$STUB"; else echo "-J-Xbootclasspath/a:$STUB"; fi
}

ALTDIR=
for cand in "${PREFIX:-}" /data/data/com.termux/files/usr; do
  if [ -n "$cand" ] && [ -d "$cand/etc/alternatives" ]; then
    ALTDIR="$cand/etc/alternatives"
    break
  fi
done

if [ -n "$ALTDIR" ]; then
  BINDIR=$(cd "$ALTDIR/../.." && pwd)   # $PREFIX/etc/alternatives -> $PREFIX
  for t in $TOOLS; do
    real=$(ls -d "$BINDIR"/lib/jvm/*/bin/"$t" 2>/dev/null | head -1)
    [ -n "$real" ] && [ -x "$real" ] || continue
    link="$ALTDIR/$t"
    [ -L "$link" ] && rm -f "$link"     # never write through the symlink: it is the real binary
    {
      echo '#!/bin/sh'
      echo "# Generated by wrap-termux-jdk.sh - Termux's OpenJDK aborts on Android without the"
      echo "# PerfettoTrace stub (libperfetto_framework_jni.so registers natives for a class"
      echo "# that only exists in the Android framework)."
      echo "exec $real $(flag_for "$t") \"\$@\""
    } > "$link"
    chmod 700 "$link"
    say "  wrapped $t -> $real"
  done
  say "  ($ALTDIR)"
else
  SHIM="$ANDROID_TOOLS/bin"
  mkdir -p "$SHIM"
  for t in $TOOLS; do
    real=$(command -v "$t" 2>/dev/null || true)
    [ -n "$real" ] && [ -x "$real" ] || continue
    case $real in "$SHIM"/*) continue ;; esac
    {
      echo '#!/bin/sh'
      echo "exec $real $(flag_for "$t") \"\$@\""
    } > "$SHIM/$t"
    chmod 700 "$SHIM/$t"
    say "  shim $t -> $real"
  done
  say "  no Termux alternatives dir; prepend to PATH: export PATH=\"$SHIM:\$PATH\""
fi
